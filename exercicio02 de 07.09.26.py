a = input('digite algo:')
print('o primitivo desse valor é',type(a))
print('é um numero?',a.isnumeric())
print('é Alfabetico?',a.isalpha())
print("é um espaço",a.isspace())
print("a letra esta maiuscula?",a.isupper())
print('a letra esta minuscula?',a.islower())
print("e alfanumerico",a.isalnum())
print("esta capitalizada",a.istitle())
